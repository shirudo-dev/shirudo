static void agent_jar_is_accepted_stored_or_deflated(void)
{
	EXPECT_EQ(jar_premain_class(stored_agent, sizeof(stored_agent)), 0);
	EXPECT_EQ(jar_premain_class(deflated_agent, sizeof(deflated_agent)),
		  0);
}

static void jar_without_premain_is_no_agent(void)
{
	EXPECT_EQ(jar_premain_class(no_premain, sizeof(no_premain)), -ENOENT);
	EXPECT_EQ(jar_premain_class(empty_premain, sizeof(empty_premain)),
		  -ENOENT);
	EXPECT_EQ(jar_premain_class(no_manifest, sizeof(no_manifest)),
		  -ENOENT);
}

/* A JVM reads the attribute from the main section only. */
static void premain_of_an_entry_section_does_not_count(void)
{
	EXPECT_EQ(jar_premain_class(premain_in_entry_section,
				    sizeof(premain_in_entry_section)),
		  -ENOENT);
}

static void file_that_is_no_zip_is_refused(void)
{
	static const __u8 text[] = "not a zip, though long enough to hold one";

	EXPECT_EQ(jar_premain_class(text, sizeof(text)), -EINVAL);
	EXPECT_EQ(jar_premain_class(text, 3), -EINVAL);
}

/* Every cut of a jar is refused or read within its bounds. */
static void truncated_jar_is_never_an_agent(void)
{
	__u8 cut[sizeof(deflated_agent)];
	size_t len;

	for (len = 0; len < sizeof(deflated_agent); len++) {
		memcpy(cut, deflated_agent, len);
		EXPECT_TRUE(jar_premain_class(cut, len) < 0);
	}
}

static void damaged_directory_is_refused(void)
{
	__u8 jar[sizeof(stored_agent)];
	size_t i;

	for (i = 0; i < sizeof(jar); i++) {
		memcpy(jar, stored_agent, sizeof(jar));
		jar[i] ^= 0xff;
		EXPECT_TRUE(jar_premain_class(jar, sizeof(jar)) <= 0);
	}
}

static const struct unit_case cases[] = {
	UNIT_CASE(agent_jar_is_accepted_stored_or_deflated),
	UNIT_CASE(jar_without_premain_is_no_agent),
	UNIT_CASE(premain_of_an_entry_section_does_not_count),
	UNIT_CASE(file_that_is_no_zip_is_refused),
	UNIT_CASE(truncated_jar_is_never_an_agent),
	UNIT_CASE(damaged_directory_is_refused),
	{}
};

UNIT_SUITE(jar, cases);
